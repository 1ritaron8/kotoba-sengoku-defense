// Curated modern Japanese vocabulary. Each map introduces a distinct set of words.
// The four ranks describe this game's progression, not JLPT certification levels.
const TARGETS = { basic: 15, beginner: 20, intermediate: 25, advanced: 30 };

function koreanParticle(word, consonant, vowel) {
  const last = word.trim().charCodeAt(word.trim().length - 1);
  return last >= 0xac00 && last <= 0xd7a3 && (last - 0xac00) % 28 !== 0 ? consonant : vowel;
}

function hiragana(text) {
  return text.replace(/[ァ-ヶ]/g, char => String.fromCharCode(char.charCodeAt(0) - 0x60));
}

function koreanQuotation(predicate) {
  return predicate.endsWith('이다') ? `${predicate.slice(0, -1)}라고` : `${predicate}고`;
}

// Kana stays outside ruby. Irregular compounds such as 今日 keep a joint reading.
function rubyParts(jp, reading) {
  const runs = jp.match(/[\p{Script=Han}々〆]+|[^\p{Script=Han}々〆]+/gu) || [jp];
  if (!runs.some(run => /[\p{Script=Han}々〆]/u.test(run))) return [{ text: jp }];
  let cursor = 0;
  const parts = [];
  for (let index = 0; index < runs.length; index += 1) {
    const run = runs[index];
    if (!/[\p{Script=Han}々〆]/u.test(run)) {
      const kana = hiragana(run);
      if (reading.slice(cursor, cursor + kana.length) !== kana) return [{ text: jp, reading }];
      parts.push({ text: run });
      cursor += kana.length;
      continue;
    }
    const nextKana = runs[index + 1] ? hiragana(runs[index + 1]) : '';
    const end = nextKana ? reading.indexOf(nextKana, cursor + 1) : reading.length;
    if (end < cursor + 1) return [{ text: jp, reading }];
    parts.push({ text: run, reading: reading.slice(cursor, end) });
    cursor = end;
  }
  return cursor === reading.length ? parts : [{ text: jp, reading }];
}

const EXAMPLES = {
  visible: (jp, reading, ko) => ({ jp: `${jp}が見えます。`, reading: `${reading}がみえます。`, ko: `${ko}${koreanParticle(ko, '이', '가')} 보입니다.` }),
  living: (jp, reading, ko) => ({ jp: `${jp}が来ました。`, reading: `${reading}がきました。`, ko: `${ko}${koreanParticle(ko, '이', '가')} 왔습니다.` }),
  provision: (jp, reading, ko) => ({ jp: `${jp}を用意します。`, reading: `${reading}をよういします。`, ko: `${ko}${koreanParticle(ko, '을', '를')} 준비합니다.` }),
  direction: (jp, reading, ko) => ({ jp: `${jp}を見てください。`, reading: `${reading}をみてください。`, ko: `${ko}${koreanParticle(ko, '을', '를')} 보세요.` }),
  quantity: (jp, reading, ko) => ({ jp: `${jp}を選んでください。`, reading: `${reading}をえらんでください。`, ko: `${ko}${koreanParticle(ko, '을', '를')} 선택하세요.` }),
  body: (jp, reading, ko) => ({ jp: `${jp}が痛いです。`, reading: `${reading}がいたいです。`, ko: `${ko}${koreanParticle(ko, '이', '가')} 아픕니다.` }),
  noun: (jp, reading, ko) => ({ jp: `${jp}について話しましょう。`, reading: `${reading}についてはなしましょう。`, ko: `${ko}에 대해 이야기해 봅시다.` }),
  verb: (jp, reading, ko) => ({ jp: `状況によって、${jp}こともあります。`, reading: `じょうきょうによって、${reading}こともあります。`, ko: `상황에 따라 ${ko.endsWith('다') ? ko.slice(0, -1) : ko}기도 합니다.` }),
  adjective: (jp, reading, ko) => ({ jp: `${jp}と感じます。`, reading: `${reading}とかんじます。`, ko: `${koreanQuotation(ko)} 느낍니다.` }),
  na: (jp, reading, ko) => ({ jp: `${jp}だと感じます。`, reading: `${reading}だとかんじます。`, ko: `${koreanQuotation(ko)} 느낍니다.` }),
};

function expression(jp, reading, ko) {
  return { jp, reading, ko, parts: rubyParts(jp, reading) };
}

function lesson(id, title, defaultKind, table, expressions) {
  const newWords = table.trim().split('\n').map((line, index) => {
    const [jp, reading, ko, kind = defaultKind, exampleJp, exampleReading, exampleKorean] = line.trim().split('|');
    if (!jp || !reading || !ko || !EXAMPLES[kind]) throw new Error(`Invalid curriculum row: ${id}/${index + 1}`);
    const exampleKo = ko.replace(/\([^)]*\)/g, '').split('·')[0].trim();
    const example = exampleJp ? { jp: exampleJp, reading: exampleReading, ko: exampleKorean } : EXAMPLES[kind](jp, reading, exampleKo);
    if (!example.reading || !example.ko) throw new Error(`Incomplete example: ${id}/${index + 1}`);
    return { id: `${id}-${String(index + 1).padStart(2, '0')}`, jp, reading, ko, parts: rubyParts(jp, reading), example: { ...example, parts: rubyParts(example.jp, example.reading) } };
  });
  return { id, title, newWords, reviewIds: [], expressions: expressions.map(item => expression(...item)) };
}

