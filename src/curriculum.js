export const CURRICULUM = { basic, beginner, intermediate, advanced };

// Review is a distinct list: recent words plus spaced words from earlier maps.
// The first map has no earlier vocabulary, so its review list is intentionally empty.
const previousWords = [];
for (const [tier, lessons] of Object.entries(CURRICULUM)) {
  for (const current of lessons) {
    const wanted = Math.min(TARGETS[tier], previousWords.length);
    const selected = new Set();
    const recentCount = Math.ceil(wanted * 0.6);
    for (let offset = 1; offset <= recentCount; offset += 1) {
      selected.add(previousWords[previousWords.length - offset].id);
    }
    const olderCount = previousWords.length - recentCount;
    const remaining = wanted - selected.size;
    for (let index = 0; index < remaining; index += 1) {
      const position = Math.floor((index + 0.5) * olderCount / remaining);
      selected.add(previousWords[position].id);
    }
    for (let index = 0; selected.size < wanted && index < previousWords.length; index += 1) {
      selected.add(previousWords[index].id);
    }
    current.reviewIds = [...selected];
    previousWords.push(...current.newWords);
  }
}

// Fail early if future edits change promised counts or accidentally repeat a word.
const seenIds = new Set();
const seenJapanese = new Set();
for (const [tier, lessons] of Object.entries(CURRICULUM)) {
  if (lessons.length !== 10) throw new Error(`${tier} must contain 10 maps.`);
  for (const current of lessons) {
    if (current.newWords.length !== TARGETS[tier]) throw new Error(`${current.id}: expected ${TARGETS[tier]} new words.`);
    if (new Set(current.reviewIds).size !== current.reviewIds.length || current.reviewIds.some(id => !seenIds.has(id))) throw new Error(`${current.id}: invalid earlier-word review.`);
    for (const word of current.newWords) {
      if (seenIds.has(word.id) || seenJapanese.has(word.jp)) throw new Error(`Duplicate vocabulary: ${word.jp}`);
      seenIds.add(word.id);
      seenJapanese.add(word.jp);
    }
  }
}
if (seenJapanese.size !== 900) throw new Error('The complete curriculum must contain 900 unique Japanese entries.');

export const WORDS_BY_ID = Object.fromEntries(previousWords.map(word => [word.id, word]));
export const CURRICULUM_STATS = Object.freeze({
  maps: 40,
  uniqueWords: seenJapanese.size,
  tiers: Object.fromEntries(Object.entries(CURRICULUM).map(([tier, lessons]) => [tier, {
    maps: lessons.length,
    newWordsPerMap: TARGETS[tier],
    uniqueWords: lessons.reduce((sum, current) => sum + current.newWords.length, 0),
  }])),
});
