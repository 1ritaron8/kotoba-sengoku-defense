def build_lookup(curriculum):
    result = {}
    for lessons in curriculum.values():
        for lesson in lessons:
            for word in lesson['newWords']:
                result.setdefault(word['jp'], word['reading'])
    result.update(EXTRA)
    for word, (stem, reading, te, te_reading) in VERBS.items():
        result[stem] = reading
        for suffix in ('ます','ません','ました','ませんでした','たいです'):
            result[stem+suffix] = reading+suffix
        result[te] = te_reading
        result[te+'います'] = te_reading+'います'
    for word, reading in list(result.items()):
        if word.endswith('い') and len(word)>1:
            base = reading[:-1]
            if word in ('良い','いい'): base = 'よ'
            result[word[:-1]+'くない'] = base+'くない'
            result[word[:-1]+'かった'] = base+'かった'
    return result

def particle(noun, kind):
    last = next((c for c in reversed(noun) if '\uac00' <= c <= '\ud7a3'), '')
    consonant = bool(last) and (ord(last)-0xac00)%28 != 0
    pairs = {'topic':('은','는'),'subject':('이','가'),'object':('을','를'),'and':('과','와')}
    return pairs[kind][0 if consonant else 1]

def text_value(jp, ko, lookup):
    parts, reading, cursor = [], '', 0
    candidates = sorted(lookup, key=len, reverse=True)
    while cursor < len(jp):
        found = next((token for token in candidates if jp.startswith(token, cursor)), None)
        if found is not None:
            pron = lookup[found]
            item = {'text': found}
            if any('\u4e00' <= c <= '\u9fff' for c in found): item['reading'] = pron
            parts.append(item)
            reading += kana(pron)
            cursor += len(found)
        else:
            character = jp[cursor]
            if '\u4e00' <= character <= '\u9fff':
                raise ValueError(f'Unreviewed kanji reading {character!r} in {jp!r}')
            if parts and 'reading' not in parts[-1]: parts[-1]['text'] += character
            else: parts.append({'text':character})
            reading += kana(character)
            cursor += 1
    return {'jp':jp, 'reading':reading, 'ko':ko, 'parts':parts}

