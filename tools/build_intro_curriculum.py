def target_span(word, sentence, lookup):
    jp = word['jp']
    special = {'一':'一つ','二':'二つ','三':'三つ','四':'四つ','五':'五つ',
               '六':'六つ','七':'七つ','八':'八つ','九':'九つ','年':'今年'}
    composite = special.get(jp,'')
    for combined in {'分':['一分','二分'],'秒':['一秒','三秒'],'週':['一週','二週'],'年':['今年','一年']}.get(jp,[]):
        if combined in sentence:
            return {'text':combined,'reading':lookup[combined],'start':sentence.index(combined),'length':len(combined),'wordId':word['id']}
    if composite and composite in sentence:
        return {'text':composite,'reading':lookup[composite],'start':sentence.index(composite),'length':len(composite),'wordId':word['id']}
    if jp in VERBS:
        stem, read, te, te_read = VERBS[jp]
        forms = [(stem+s,read+s) for s in ('ませんでした','たいです','ました','ません','ます')]
        forms += [(te+'います',te_read+'います'),(te,te_read),(jp,word['reading'])]
    elif jp.endswith('い') and len(jp)>1:
        negative = jp[:-1]+'くない'
        forms = [(negative,lookup[negative]),(jp,word['reading'])]
    else: forms = [(jp,word['reading'])]
    for form, reading in forms:
        if form in sentence:
            start = sentence.index(form)
            if jp=='分': reading = 'ぷん' if start>0 and sentence[start-1]=='一' else 'ふん'
            return {'text':form,'reading':reading,'start':start,'length':len(form),'wordId':word['id']}
    raise ValueError(f'No actual target span: {word["id"]} in {sentence}')

