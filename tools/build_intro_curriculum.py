def assessment(step, key, index, lookup):
    span_text,span_reading,options = ASSESSMENTS[key]
    item = copy.deepcopy(step['example'])
    jp = item['jp']
    start = jp.index(span_text)
    span = {'text':span_text,'reading':span_reading,'start':start,'length':len(span_text)}
    choices = []
    for number,(text,meaning) in enumerate(options):
        pron = span_reading if number==0 else lookup.get(text,kana(text))
        if any('\u4e00'<=c<='\u9fff' for c in text) and pron==text:
            # Deliberately malformed inflection distractors still have a
            # correctly pronounced visible character sequence.
            prefixes = [('大き','おおき'),('小さ','ちいさ'),('寒','さむ'),('作り','つくり'),('作る','つくる'),('開け','あけ'),('開ける','あける'),('休み','やすみ'),('休む','やすむ'),('行く','いく')]
            for prefix,reading in prefixes:
                if text.startswith(prefix): pron = reading+kana(text[len(prefix):]); break
        value = {'jp':text,'reading':pron,'ko':meaning,'parts':[{'text':text,'reading':pron}]}
        value['id'] = step['id']+'-choice-'+str(number)
        choices.append(value)
    shift = index%len(choices)
    choices = choices[shift:]+choices[:shift]
    return {'item':item,'targetSpan':span,'choices':choices,'answerId':step['id']+'-choice-0',
            'explanationKo':step['explanationKo'],'cueKo':'다음 뜻에 맞게 빈칸을 채우세요: '+item['ko']}

def used_grammar(jp, order, ordered_steps):
    # Explicit surface-pattern map. No whole-history tags: the final ID is
    # the most recently introduced grammar actually visible in this sentence.
    has_no = any(c=='の' and (i==0 or jp[i-1] not in 'こそあ') for i,c in enumerate(jp)) and 'きのこ' not in jp
    predicates = {
      'nominal':lambda: jp.endswith('です。') and not any(s in jp for s in ('いです','くないです','かったです','たいです')),
      'topic':lambda:'は' in jp,
      'demonstrative':lambda:any(s in jp for s in ('これ','それ','あれ','この','その','あの')),
      'no':lambda:has_no,
      'place':lambda:any(s in jp for s in ('ここ','そこ')),
      'location_no':lambda:has_no and any(s in jp for s in ('門','城','部屋','家','村','町','庭','窓','屋根','床','階段')),
      'and':lambda:'と' in jp and not any(s in jp for s in ('戻','友達と','父と','母と','兄と','姉と','弟と','妹と','先生と','学生と','家族と')),
      'also':lambda:'も' in jp,
      'location':lambda:'に' in jp and 'あります' in jp,
      'direction':lambda:'へ' in jp,
      'quantity':lambda:any(s in jp for s in ('一つ','二つ','三つ','四つ','五つ','六つ','七つ','八つ','九つ')),
      'amount':lambda:'半分' in jp or '全部' in jp,
      'time':lambda:any(s in jp for s in ('今','今日','明日','昨日','毎日','朝','昼','夜','夕方')),
      'time_relation':lambda:has_no and any(s in jp for s in ('朝','昼','夜','明日','今日','昨日','毎日','夕方')),
      'i_adjective':lambda:any(w+'です' in jp for w in ('大きい','小さい','長い','短い','広い','細い','強い','低い','寒い','暑い','暖かい','涼しい','明るい','暗い','高い','太い','重い','軽い','速い','遅い','新しい','古い','多い','少ない','良い','悪い')),
      'adjective_noun':lambda:any(w in jp and w+'です' not in jp for w in ('大きい','小さい','長い','短い','広い','細い','強い')),
      'living':lambda:'います' in jp and 'ています' not in jp and 'でいます' not in jp,
      'living_location':lambda:'に' in jp and 'います' in jp and 'ています' not in jp and 'でいます' not in jp,
      'masu':lambda:'ます' in jp and 'ています' not in jp and 'でいます' not in jp,
      'object':lambda:'を' in jp,
      'noun_negative':lambda:'ではありません' in jp,
      'masu_negative':lambda:'ません' in jp and 'ではありません' not in jp,
      'question':lambda:jp.endswith('か。'),
      'where':lambda:'どこ' in jp or '何' in jp,
      'action_place':lambda:any(s+'で' in jp for s in ('店','市場','村','城','森','港','交差点','ここ')),
      'tool':lambda:any(s+'で' in jp for s in ('筆','墨','布','箸','包丁','鍋','杯','盾')),
      'from_to':lambda:'から' in jp or 'まで' in jp,
      'na_adjective':lambda:'静か' in jp or 'きれい' in jp,
      'request':lambda:'ください' in jp,
      'weather':lambda:any(s in jp for s in ('天気','気温','季節','晴れ','曇り','暑い','寒い','暖かい','涼しい','明るい','暗い')),
      'past_action':lambda:'ました' in jp,
      'past_noun':lambda:'でした' in jp and 'ませんでした' not in jp,
      'adjective_negative':lambda:'くない' in jp,
      'adjective_past':lambda:'かった' in jp,
      'te_godan':lambda:any(data[2] in jp for word,data in VERBS.items() if word not in ('見る','食べる','集める','開ける','閉める','出る','降りる','攻める','助ける','逃げる','隠れる','決める','始める','続ける','調べる','増える','練習する','来る')),
      'te_ichidan':lambda:any(VERBS[word][2] in jp for word in ('見る','食べる','集める','開ける','閉める','出る','降りる','攻める','助ける','逃げる','隠れる','決める','始める','続ける','調べる','増える','練習する','来る')),
      'ongoing':lambda:'ています' in jp or 'でいます' in jp,
      'sequence':lambda:'て、' in jp or 'で、' in jp,
      'together':lambda:any(s+'と' in jp for s in ('友達','父','母','兄','姉','弟','妹','先生','学生','家族')),
      'desire':lambda:'たい' in jp,
    }
    return [s['id'] for position,s in ordered_steps if position<=order and predicates[s['introducedPatterns'][0]]()]

