def hira(value: str) -> str:
    return ''.join(chr(ord(c)-0x60) if '\u30a1'<=c<='\u30f6' else c for c in value)

def text(value: str, ko: str) -> dict:
    parts, jp, reading, cursor = [], [], [], 0
    for match in RUBY.finditer(value):
        literal = value[cursor:match.start()]
        if literal:
            assert not HAN.search(literal), (value, literal)
            parts.append({'text': literal})
            jp.append(literal); reading.append(hira(literal))
        body, kana = match.groups()
        parts.append({'text':body,'reading':kana})
        jp.append(body); reading.append(kana)
        cursor = match.end()
    literal = value[cursor:]
    if literal:
        assert not HAN.search(literal), (value,literal)
        parts.append({'text':literal}); jp.append(literal); reading.append(hira(literal))
