def distance(a,b):
    return math.hypot(a['x']-b['x'],a['y']-b['y'])

def choose_zones(stage):
    zones = stage['buildZones']
    candidates = [(i,z) for i,z in enumerate(zones) if .10<=z['x']<=.90 and .10<=z['y']<=.90]
    if len(candidates)<3: candidates=list(enumerate(zones))
    def score(combo):
        points=[p[1] for p in combo]
        separation=min(distance(a,b) for a,b in itertools.combinations(points,2))
        # Enough label room is mandatory when available; afterwards prefer
        # wide spread over coincident labels along narrow routes.
        return (separation>=.22,separation,sum(distance(a,b) for a,b in itertools.combinations(points,2)))
    chosen=max(itertools.combinations(candidates,3),key=score)
    xrange=max(z['x'] for _,z in chosen)-min(z['x'] for _,z in chosen)
    yrange=max(z['y'] for _,z in chosen)-min(z['y'] for _,z in chosen)
    axis='x' if xrange>=.40 or xrange>=yrange else 'y'
    return sorted(chosen,key=lambda p:p[1][axis]),axis

def _author_plans(curriculum,maps):
    words={w['jp']:w for lessons in curriculum.values() for l in lessons for w in l['newWords']}
    ordinal={w['id']:i for i,w in enumerate(w for lessons in curriculum.values() for lesson in lessons for w in lesson['newWords'])}
    stages={}
    index_by_tier={}
    for stage_number,stage in enumerate(maps):
        tier=stage['tier']; index=index_by_tier.get(tier,0); index_by_tier[tier]=index+1
        lesson=curriculum[tier][index]
        authored=SPECS[stage['id']]
        chosen,axis=choose_zones(stage)
        names=[('左{ひだり}の支援点{しえんてん}','왼쪽 지원점'),('中央{ちゅうおう}の支援点{しえんてん}','중앙 지원점'),('右{みぎ}の支援点{しえんてん}','오른쪽 지원점')] if axis=='x' else [('上{うえ}の支援点{しえんてん}','위쪽 지원점'),('中央{ちゅうおう}の支援点{しえんてん}','중앙 지원점'),('下{した}の支援点{しえんてん}','아래쪽 지원점')]
        if stage['id']=='basic-forest':
            names=[('森{もり}','숲'),('川{かわ}','강'),('山{やま}','산')]
        targets=[{'id':f'zone-{i:02d}','position':{'x':z['x'],'y':z['y']},'label':text(*label)} for (i,z),label in zip(chosen,names)]
        # The same wave cannot be solved by always clicking the same screen
        # position across maps. Requests and correct destinations vary together.
        permutation=list(itertools.permutations(range(3)))[stage_number%6]
        token_names=[names[i] for i in permutation]
        missions=[]
        for mission_index,(wave,answer_index,report,focus) in enumerate(zip([1,3,6],[0,2,1],authored['reports'],authored['focus'])):
            jp,ko=report
            for token,(annotated,meaning) in zip(['@A@','@B@','@C@'],token_names):
                jp=jp.replace(token,annotated); ko=ko.replace(token,meaning)
            answer=targets[permutation[answer_index]]
            report_data=text(jp,ko)
            item_ids=[words[focus]['id']] if focus in words else []
            # A report may introduce an annotated expression before its word
            # lesson, but it cannot silently grant mastery to future words.
            last_visible=ordinal[lesson['newWords'][-1]['id']]
            item_ids=[word_id for word_id in item_ids if ordinal[word_id]<=last_visible]
            # Only an explicit lexical focus is credited; none of the other
            # words in the sentence automatically earn context proficiency.
            missions.append({'id':f"{stage['id']}-context-{mission_index+1}",'wave':wave,'report':report_data,'targets':targets,'answerId':answer['id'],'successKo':f"{answer['label']['ko']}에 지원을 보냈습니다. 보고의 요청을 이해했습니다.",'action':{'kind':'support','position':answer['position']},'itemIds':item_ids})
        stages[stage['id']]={'lessonId':lesson['id'],'tier':tier,'goalKo':authored['goal'],'grammar':[{'jp':j,'ko':k} for j,k in authored['grammar']],'missions':missions}
    return {'version':1,'stages':stages}

def _same_point(a, b):
    return distance(a, b) < .00001

def _direction_axis(labels):
    japanese = [label['jp'] for label in labels]
    if japanese == ['左の支援点', '中央の支援点', '右の支援点']:
        return 'x'
    if japanese == ['上の支援点', '中央の支援点', '下の支援点']:
        return 'y'
    if japanese == ['森', '川', '山']:
        return None
    raise ValueError(f'Unknown authored destination meanings: {japanese}')

def _display_candidates(stage, runtime):
    """Use actual Game/Nav observations, never a second orientation policy."""
    candidates = []
    zones = stage['buildZones']
    observed = runtime['candidates']
    if len(observed) != len(zones):
        raise ValueError(f"{stage['id']}: coordinate snapshot omits build zones")
    for index, (zone, sample) in enumerate(zip(zones, observed)):
        if sample['zoneIndex'] != index or sample['zoneId'] != zone['id'] or not _same_point(zone, sample['canonical']):
            raise ValueError(f"{stage['id']}: stale coordinate snapshot for zone {index}")
        point = {'x': zone['x'], 'y': zone['y']}
        if not all(math.isfinite(point[axis]) and .10 <= point[axis] <= .90 for axis in ['x', 'y']):
            continue
        if sample.get('landSafe') is not True or sample.get('margin') != .008:
            continue
        candidates.append({'index': index, 'position': point, 'displayed': sample['displayed']})
    return candidates

def _bind_destinations(stage, authored, runtime, rebind_anchors):
    missions = authored['missions']
    if len(missions) != 3:
        raise ValueError(f"{stage['id']}: preserve exactly three authored reports")
    labels = [target['label'] for target in missions[0]['targets']]
    if len(labels) != 3:
        raise ValueError(f"{stage['id']}: preserve three destination meanings")
    axis = _direction_axis(labels)
    for mission in missions:
        if [target['label'] for target in mission['targets']] != labels:
            raise ValueError(f"{stage['id']}: authored reports do not share destination meanings")
    anchors = stage.get('historicalBattlefield', {}).get('learningSupportAnchors', {})
    required = {}
    for mission in missions:
        answer = next(target for target in mission['targets'] if target['id'] == mission['answerId'])
        rank = labels.index(answer['label'])
        if mission['id'] not in anchors or rebind_anchors:
            continue
        location = anchors[mission['id']]
        sample = runtime.get('learningSupportAnchors', {}).get(mission['id'], {})
        if not _same_point(location, sample.get('canonical', {'x': -1, 'y': -1})) or sample.get('landSafe') is not True:
            raise ValueError(f"{mission['id']}: actual Main support override is stale or not land-safe")
        if rank in required and not _same_point(required[rank], location):
            raise ValueError(f"{stage['id']}: one destination meaning has conflicting Main support points")
        required[rank] = location
    candidates = _display_candidates(stage, runtime)
    valid = []
    for combination in itertools.combinations(candidates, 3):
        ordered = sorted(combination, key=lambda candidate: (candidate['displayed'][axis or 'x'], candidate['index']))
        if any(not _same_point(ordered[rank]['position'], location) for rank, location in required.items()):
            continue
        separation = min(distance(a['position'], b['position']) for a, b in itertools.combinations(ordered, 2))
        if separation < .22:
            continue
        gaps = [ordered[index+1]['displayed'][axis or 'x']-ordered[index]['displayed'][axis or 'x'] for index in range(2)]
        if axis is not None and min(gaps) <= .00001:
            continue
        spread = sum(distance(a['position'], b['position']) for a, b in itertools.combinations(ordered, 2))
        # All options remain separated by the original .22 map-space contract.
        # Prefer visibly distinct positions along the authored direction axis.
        valid.append(((min(gaps) >= .12, min(gaps), separation, spread), ordered))
    if not valid:
        raise ValueError(f"{stage['id']}: no land-safe .22-separated {axis or 'natural-word'} destinations agree with actual Main support anchors; maps writer must rebind those anchors")
    chosen = max(valid, key=lambda entry: entry[0])[1]
    targets = [{'id': f"zone-{candidate['index']:02d}", 'position': candidate['position'], 'label': copy.deepcopy(label)} for candidate, label in zip(chosen, labels)]
    recommendations = {}
    for mission in missions:
        old_answer = next(target for target in mission['targets'] if target['id'] == mission['answerId'])
        answer = next(target for target in targets if target['label'] == old_answer['label'])
        mission['targets'] = copy.deepcopy(targets)
        mission['answerId'] = answer['id']
        mission['action']['position'] = copy.deepcopy(answer['position'])
        if mission['id'] in anchors:
            recommendations[mission['id']] = copy.deepcopy(answer['position'])
            if not rebind_anchors and not _same_point(answer['position'], anchors[mission['id']]):
                raise ValueError(f"{mission['id']}: selected picture and actual Main support differ")
    return recommendations

def build_plans(curriculum, maps, existing_plans=None, layout_contract=None, rebind_anchors=False):
    """Rebind destinations while preserving every authored report/ruby/credit.

    Coordinate snapshots are exported by qa_learning_direction_contract.gd
    from the common runtime helper and Nav. Advice is tests-only: the sole maps
    writer applies its nine anchor records before the production plans rebuild.
    """
    if layout_contract is None:
        raise ValueError('Actual Game/Presentation coordinate snapshot is required')
    plans = copy.deepcopy(existing_plans if existing_plans is not None else _author_plans(curriculum, maps))
    if set(plans['stages']) != {stage['id'] for stage in maps} or set(layout_contract['stages']) != set(plans['stages']):
        raise ValueError('Authored plans, maps and runtime coordinate snapshot must cover the same forty stages')
    recommendations = {}
    for stage in maps:
        values = _bind_destinations(stage, plans['stages'][stage['id']], layout_contract['stages'][stage['id']], rebind_anchors)
        if values:
            recommendations[stage['id']] = values
    return plans, recommendations

def word_annotated(word):
    return ''.join(p['text']+'{'+p['reading']+'}' if p.get('reading') else p['text'] for p in word['parts'])

def add_transfer_examples(curriculum):
    count=0
    for lessons in curriculum.values():
        for lesson in lessons:
            lines=TRANSFER[lesson['id']]
            assert len(lines)==len(lesson['newWords']), (lesson['id'],len(lines),len(lesson['newWords']))
            for word,(jp,ko) in zip(lesson['newWords'],lines):
                if word['id']=='beginner-07-16':
                    # Existing Korean adjective quotation used an invalid
                    # form '오래되다고'; keep the Japanese example unchanged.
                    word['example']['ko']='오래되었다고 느낍니다.'
                try:
                    sentence=text(jp.replace('@',word_annotated(word)),ko)
                except AssertionError as error:
                    raise ValueError(f"{word['id']} transfer: {error}") from error
                assert sentence['jp']!=word['example']['jp'], word['id']
                word['transferExample']=sentence
                count+=1
    return count

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--plans-only',action='store_true')
    parser.add_argument('--maps',type=Path,default=ROOT/'native/maps.json')
    parser.add_argument('--plans-source',type=Path,default=ROOT/'native/learning_plans.json')
    parser.add_argument('--layout-contract',type=Path,required=True)
    parser.add_argument('--output',type=Path,default=ROOT/'native/learning_plans.json')
    parser.add_argument('--recommend-anchors',type=Path)
    parser.add_argument('--dry-run',action='store_true')
    args=parser.parse_args()
    if not args.plans_only:
        parser.error('Layout rebinding requires --plans-only; original curriculum/grammar/transfer examples must be preserved')
    curriculum=json.loads((ROOT/'native/curriculum.json').read_text(encoding='utf-8'))
    maps=json.loads(args.maps.read_text(encoding='utf-8'))
    contract=json.loads(args.layout_contract.read_text(encoding='utf-8'))
    if contract.get('mapsSha256') != hashlib.sha256(args.maps.read_bytes()).hexdigest():
        raise ValueError('Runtime coordinate snapshot does not match the selected maps bytes')
    for key,path in [('presentationSha256','native/battlefield_presentation.gd'),('gameSha256','native/game.gd')]:
        if contract.get(key) != hashlib.sha256((ROOT/path).read_bytes()).hexdigest():
            raise ValueError(f'Stale runtime coordinate authority: {path}')
    existing=json.loads(args.plans_source.read_text(encoding='utf-8')) if args.plans_source.exists() else None
    if existing is not None and 'plans' in existing: existing=existing['plans']
    transfer_count=0
    plans,recommendations=build_plans(curriculum,maps,existing,contract,args.recommend_anchors is not None)
    if args.recommend_anchors is not None:
        advice=args.recommend_anchors.resolve()
        if not advice.is_relative_to((ROOT/'tests/profiles').resolve()):
            raise ValueError('Anchor advice is isolated tests-only output; production maps are owned by the maps writer')
        advice.parent.mkdir(parents=True,exist_ok=True)
        advice.write_text(json.dumps({'mapsSha256':contract['mapsSha256'],'coordinateAuthority':contract['coordinateAuthority'],'stages':recommendations},ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    elif not args.dry_run:
        if args.maps.resolve() != (ROOT/'native/maps.json').resolve() and args.output.resolve() == (ROOT/'native/learning_plans.json').resolve():
            raise ValueError('Private draft cannot replace production learning plans before the maps writer publishes it')
        args.output.write_text(json.dumps(plans,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({'stages':len(plans['stages']),'missions':sum(len(s['missions']) for s in plans['stages'].values()),'linkedMissions':sum(bool(m['itemIds']) for s in plans['stages'].values() for m in s['missions']),'transferExamplesAdded':transfer_count,'preservedAuthoredReports':existing is not None,'mapsSha256':contract['mapsSha256'],'anchorRecommendations':sum(len(values) for values in recommendations.values()),'dryRun':args.dry_run},ensure_ascii=False))

if __name__=='__main__': main()
